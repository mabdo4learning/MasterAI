// Writes the "Colour themes" CSS in src/styles.css from src/lib/accents.ts.
// Run: node --experimental-strip-types scripts/accents-css.mjs
import fs from 'node:fs';
import { ACCENTS, DEFAULT_ACCENT } from '../src/lib/accents.ts';

const START = '/* ---------- Colour themes (generated by scripts/accents-css.mjs — edit src/lib/accents.ts) ---------- */';
const END = '/* ---------- end colour themes ---------- */';
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)).join(', ');

const inkVars = (a) => `  --ink-bright: ${a.ink.bright};
  --ink-hi: ${a.ink.hi};
  --ink-deep: ${a.ink.deep};
  --ink-lo: ${a.ink.lo};
  --ink-rgb: ${rgb(a.ink.lo)};
  --on-ink-hi: ${a.onInk.text};
  --ink-gold: ${a.onInk.ring};
  --metal-hi: ${a.onInk.metalHi};
  --metal-lo: ${a.onInk.metalLo};
  --glow-rgb: ${a.glow};
  --glow-2-rgb: ${a.glow2};`;
const darkVars = (a) => `  --accent: ${a.dark.accent};
  --on-accent: ${a.dark.onAccent};
  --gold: ${a.dark.gold};
  --gold-soft: ${a.dark.goldSoft};`;

const base = ACCENTS.find((a) => a.id === DEFAULT_ACCENT);
const blocks = [`/* ${base.name} is the default: its accent is in the theme tokens at the top of this file. */\n:root {\n${inkVars(base)}\n}`];
for (const a of ACCENTS) {
  if (a.id === DEFAULT_ACCENT) continue;
  const sel = `:root[data-accent='${a.id}']`;
  blocks.push(`/* ${a.name} — ${a.note} */
${sel} {
  --accent: ${a.light.accent};
  --on-accent: #fffcf6;
  --gold: ${a.light.gold};
  --gold-soft: ${a.light.goldSoft};
  --ink: ${a.ink.deep};
${inkVars(a)}
}
@media (prefers-color-scheme: dark) {
  ${sel}:not([data-theme='light']) {
${darkVars(a).replace(/^/gm, '  ')}
  }
}
${sel}[data-theme='dark'] {
${darkVars(a)}
}`);
}

const file = new URL('../src/styles.css', import.meta.url);
let css = fs.readFileSync(file, 'utf8');
const section = `${START}\n${blocks.join('\n\n')}\n${END}`;
const i = css.indexOf(START);
const j = css.indexOf(END);
css = i >= 0 && j > i ? css.slice(0, i) + section + css.slice(j + END.length) : `${css.trimEnd()}\n\n${section}\n`;
fs.writeFileSync(file, css);
console.log(`Wrote ${ACCENTS.length} colour themes to src/styles.css`);
